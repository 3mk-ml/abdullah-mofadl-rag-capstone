"""Download the prebuilt RAG retrieval index instead of indexing in Streamlit.

The index is generated by GitHub Actions and distributed as a public GitHub
Release asset. This keeps PDF downloads and 5k+ passage embeddings off the
small Streamlit Community Cloud app.
"""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import tempfile
import time
import zipfile
from pathlib import Path

import requests

from .config import INDEX_DIR

REPO = "3mk-ml/abdullah-mofadl-rag-capstone"
RELEASE_TAG = "agrirag-streamlit-index-v1"
ARCHIVE_NAME = "agrirag-index-v1.zip"
BASE_URL = f"https://github.com/{REPO}/releases/download/{RELEASE_TAG}"
MAX_ARCHIVE_BYTES = 350 * 1024 * 1024
MAX_UNCOMPRESSED_BYTES = 700 * 1024 * 1024


def _index_ready(path: Path = INDEX_DIR) -> bool:
    """Fast file-level check for the complete prebuilt hybrid-search index."""
    chunks = path / "chunks.jsonl"
    bm25 = path / "bm25.pkl"
    chroma = path / "chroma" / "chroma.sqlite3"
    if not all(p.is_file() and p.stat().st_size > 0 for p in (chunks, bm25, chroma)):
        return False
    with chunks.open("rb") as f:
        count = sum(1 for line in f if line.strip())
    return count >= 1000


def _download(session: requests.Session, url: str, destination: Path, limit: int) -> None:
    last_error: Exception | None = None
    for attempt in range(3):
        try:
            with session.get(url, timeout=(20, 120), stream=True, allow_redirects=True) as r:
                r.raise_for_status()
                total = 0
                with destination.open("wb") as f:
                    for chunk in r.iter_content(chunk_size=1024 * 1024):
                        if not chunk:
                            continue
                        total += len(chunk)
                        if total > limit:
                            raise ValueError("Prebuilt index download exceeded expected size limit")
                        f.write(chunk)
            return
        except (requests.RequestException, OSError) as exc:
            last_error = exc
            if attempt < 2:
                time.sleep(2 * (attempt + 1))
    raise RuntimeError(f"Could not download prebuilt AgriRAG index: {last_error}") from last_error


def _unpack_verified(archive: Path, destination: Path) -> None:
    with zipfile.ZipFile(archive) as zf:
        files = zf.infolist()
        if sum(x.file_size for x in files) > MAX_UNCOMPRESSED_BYTES:
            raise ValueError("Prebuilt index archive is too large when unpacked")
        for item in files:
            p = Path(item.filename)
            if p.is_absolute() or ".." in p.parts or p.parts[:2] != ("data", "index"):
                raise ValueError(f"Unsafe archive member: {item.filename}")
            if ((item.external_attr >> 16) & 0o170000) == 0o120000:
                raise ValueError("Archive must not contain symlinks")
        zf.extractall(destination)


def ensure_prebuilt_index() -> None:
    if _index_ready():
        print("Prebuilt AgriRAG index already present", flush=True)
        return

    archive_url = f"{BASE_URL}/{ARCHIVE_NAME}"
    checksum_url = archive_url + ".sha256"
    session = requests.Session()
    session.headers.update({"User-Agent": "AgriRAG-Streamlit/1.0"})
    with tempfile.TemporaryDirectory(prefix="agrirag-index-") as scratch:
        scratch_dir = Path(scratch)
        checksum_file = scratch_dir / (ARCHIVE_NAME + ".sha256")
        archive_file = scratch_dir / ARCHIVE_NAME
        print("Downloading verified, prebuilt AgriRAG search index...", flush=True)
        _download(session, checksum_url, checksum_file, 1024)
        expected = checksum_file.read_text(encoding="utf-8").split()[0].lower()
        if not re.fullmatch(r"[0-9a-f]{64}", expected):
            raise ValueError("Invalid prebuilt index checksum")
        _download(session, archive_url, archive_file, MAX_ARCHIVE_BYTES)
        digest = hashlib.file_digest(archive_file.open("rb"), "sha256").hexdigest()
        if digest != expected:
            raise ValueError("Prebuilt index failed SHA256 verification")

        stage = scratch_dir / "unpacked"
        _unpack_verified(archive_file, stage)
        staged_index = stage / "data" / "index"
        if not _index_ready(staged_index):
            raise ValueError("Downloaded index is missing required Chroma/BM25/chunks files")

        INDEX_DIR.parent.mkdir(parents=True, exist_ok=True)
        if INDEX_DIR.exists():
            shutil.rmtree(INDEX_DIR)
        shutil.move(str(staged_index), str(INDEX_DIR))
        print("Prebuilt AgriRAG knowledge index is ready", flush=True)
